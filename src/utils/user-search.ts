export function matchesUserSearch(user: SearchableUser, query: string): boolean {
  const terms=normalize(query).split(/\s+/).filter(Boolean);
  const name=normalize(user.first_name || "");
  const text=normalize([user.last_name,user.first_name,user.middle_name,user.login].filter(Boolean).join(" "));
  const aliases=groups.filter(group=>group.includes(name)).flat();
  return terms.every(term=>text.includes(term) || aliases.some(alias=>alias.startsWith(term)));
}
